/**
 * Builds the "Çıkmış TUS Denemeleri" pack the app installs as decks (lib/pastExams.ts).
 *
 * Input is the question bank of the TUSBuddy reconstruction project: 11,604 questions from 54
 * TUS exams, each with five options, its key, course and unit, and the figures its stem shows.
 * Output is one zip — `questions.json` plus the figures under an Anki-style `media` manifest —
 * and a small manifest the deck list reads for its counts without opening the zip.
 *
 * None of the output is committed. The questions are ÖSYM's work and may not be redistributed
 * without its written permission, so a build only carries the pack when someone entitled to ship
 * it has run this script; without it the deck list simply does not offer the exams.
 *
 * The explanations in that bank were written by TUSBuddy, not ÖSYM, so they stay out of the
 * pack unless --with-explanations is passed by someone entitled to ship them.
 *
 * Run with: npm run build:past-exams -- --source /path/to/rea-tusbuddy [--with-explanations]
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import JSZip from 'jszip';
import {
    PAST_EXAM_PACK_FORMAT,
    comparePastExamQuestions,
    parsePastExamPack,
    buildPastExamManifest,
    type PastExamQuestion,
} from '../lib/pastExamPack.ts';

const PACK_PATH = 'assets/catalog/cikmis-tus.zip';
const MANIFEST_PATH = 'assets/catalog/cikmis-tus-manifest.json';
/** Metro resolves `tus-past-exam-pack` to this file when it exists (metro.config.js). */
const LOADER_PATH = 'assets/catalog/cikmis-tus-pack.js';
const LOADER_SOURCE = `// Generated by scripts/build-past-exam-pack.ts. The questions are ÖSYM's.
module.exports = {
    manifest: require('./cikmis-tus-manifest.json'),
    asset: require('./cikmis-tus.zip'),
};
`;
const BANK_PATH = 'ios/TusBuddy/Features/Preparation/question-bank.json';
const MEDIA_INDEX_PATH = 'ios/TusBuddy/Features/Preparation/question-media-index.json';
const MEDIA_DIR = 'ios/TusBuddy/Resources/QuestionMedia';

const EXTENSION_BY_MIME: Record<string, string> = {
    'image/jpeg': 'jpg',
    'image/png': 'png',
    'image/webp': 'webp',
    'image/gif': 'gif',
};

interface SourceQuestion {
    id: number;
    course: string;
    unit: string;
    year: number;
    examNumber: number;
    order: number;
    stemHTML: string;
    optionsHTML: string[];
    answer: string;
    solutionHTML: string | null;
    optionExplanationsHTML: string[] | null;
    examTipsHTML: string | null;
    tablesHTML: string[];
}

interface MediaIndexEntry {
    file: string;
    mime: string;
    sha256: string;
}

function argument(name: string): string | null {
    const index = process.argv.indexOf(name);
    return index >= 0 ? process.argv[index + 1] ?? null : null;
}

function sha256(bytes: Uint8Array | string): string {
    return createHash('sha256').update(bytes).digest('hex');
}

class MediaCollector {
    readonly files = new Map<string, Uint8Array>();
    private readonly byUrl = new Map<string, string>();
    // Plain fields rather than parameter properties: Node's type stripping cannot run those.
    private readonly index: Record<string, MediaIndexEntry>;
    private readonly mediaDir: string;

    constructor(index: Record<string, MediaIndexEntry>, mediaDir: string) {
        this.index = index;
        this.mediaDir = mediaDir;
    }

    /** The pack's filename for an image URL, or null when the bank has no bytes for it. */
    resolve(url: string): string | null {
        const known = this.byUrl.get(url);
        if (known) return known;
        const entry = this.index[url];
        if (!entry) return null;
        const source = path.join(this.mediaDir, entry.file);
        if (!existsSync(source)) return null;
        const bytes = new Uint8Array(readFileSync(source));
        if (sha256(bytes) !== entry.sha256) throw new Error(`Görsel bozuk: ${entry.file}`);
        const extension = EXTENSION_BY_MIME[entry.mime];
        if (!extension) throw new Error(`Desteklenmeyen görsel türü: ${entry.mime} (${entry.file})`);
        const filename = `tus-cikmis-${entry.sha256.slice(0, 16)}.${extension}`;
        this.files.set(filename, bytes);
        this.byUrl.set(url, filename);
        return filename;
    }
}

/**
 * The bank keeps the booklet's line breaks as newlines and its images as remote URLs. A card needs
 * `<br>` for the former and a bare media filename for the latter; the TUSBuddy-specific image
 * attributes are dropped with them.
 */
function cleanHtml(html: string, media: MediaCollector, onMissingImage: 'fail' | 'drop', label: string): string {
    return html
        .replace(/\r\n?/g, '\n')
        .trim()
        .replace(/<img\b[^>]*?\bsrc="([^"]+)"[^>]*>/gi, (_tag, url: string) => {
            const filename = media.resolve(url);
            if (filename) return `<img src="${filename}">`;
            if (onMissingImage === 'fail') throw new Error(`${label}: görsel bulunamadı (${url}).`);
            return '';
        })
        .replace(/\n/g, '<br>');
}

function explanationHtml(source: SourceQuestion, media: MediaCollector): string | undefined {
    const label = `#${source.id} açıklaması`;
    const parts: string[] = [];
    if (source.solutionHTML?.trim()) parts.push(cleanHtml(source.solutionHTML, media, 'drop', label));
    const optionNotes = (source.optionExplanationsHTML ?? [])
        .map((html, index) => (html?.trim() ? `<li><b>${'ABCDE'[index]})</b> ${cleanHtml(html, media, 'drop', label)}</li>` : ''))
        .filter(Boolean);
    if (optionNotes.length > 0) parts.push(`<p><b>Seçenekler</b></p><ul>${optionNotes.join('')}</ul>`);
    if (source.examTipsHTML?.trim()) parts.push(`<p><b>Sınav ipuçları</b></p>${cleanHtml(source.examTipsHTML, media, 'drop', label)}`);
    for (const table of source.tablesHTML ?? []) {
        if (table.trim()) parts.push(cleanHtml(table, media, 'drop', label).replace(/(<br>)+/g, ''));
    }
    return parts.length > 0 ? parts.join('<hr>') : undefined;
}

async function main(): Promise<void> {
    const sourceRoot = argument('--source');
    if (!sourceRoot) throw new Error('Kaynak klasör gerekli: --source /path/to/rea-tusbuddy');
    const withExplanations = process.argv.includes('--with-explanations');

    const bank = JSON.parse(readFileSync(path.join(sourceRoot, BANK_PATH), 'utf8')) as SourceQuestion[];
    const mediaIndex = JSON.parse(readFileSync(path.join(sourceRoot, MEDIA_INDEX_PATH), 'utf8')) as Record<string, MediaIndexEntry>;
    const media = new MediaCollector(mediaIndex, path.join(sourceRoot, MEDIA_DIR));

    const questions: PastExamQuestion[] = bank.map((source) => {
        const label = `#${source.id}`;
        const explanation = withExplanations ? explanationHtml(source, media) : undefined;
        return {
            id: source.id,
            year: source.year,
            exam: source.examNumber,
            number: source.order,
            course: source.course.trim(),
            unit: source.unit.trim(),
            stem: cleanHtml(source.stemHTML, media, 'fail', label),
            options: source.optionsHTML.map((option) => cleanHtml(option, media, 'fail', label)),
            answer: source.answer.trim().toUpperCase() as PastExamQuestion['answer'],
            ...(explanation ? { explanation } : {}),
        };
    }).sort(comparePastExamQuestions);

    // The same check the app runs before installing: a pack it would reject is never written.
    const pack = parsePastExamPack({ format: PAST_EXAM_PACK_FORMAT, questions });
    const questionsJson = JSON.stringify(pack);

    const zip = new JSZip();
    zip.file('questions.json', questionsJson, { compression: 'DEFLATE', compressionOptions: { level: 9 } });
    const mediaManifest: Record<string, string> = {};
    [...media.files.entries()].sort(([left], [right]) => left.localeCompare(right)).forEach(([filename, bytes], index) => {
        mediaManifest[String(index)] = filename;
        // Images are already compressed; storing them keeps the install from inflating them twice.
        zip.file(String(index), bytes, { compression: 'STORE' });
    });
    zip.file('media', JSON.stringify(mediaManifest), { compression: 'DEFLATE' });
    const zipBytes = await zip.generateAsync({ type: 'uint8array', platform: 'UNIX' });
    writeFileSync(PACK_PATH, zipBytes);

    const manifest = buildPastExamManifest(pack, media.files.size, sha256(questionsJson).slice(0, 16));
    writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
    writeFileSync(LOADER_PATH, LOADER_SOURCE);

    const megabytes = (zipBytes.length / (1024 * 1024)).toFixed(2);
    console.log(`${pack.questions.length} soru, ${manifest.exams.length} sınav, ${media.files.size} görsel → ${PACK_PATH} (${megabytes} MB)`);
    if (!withExplanations) console.log('Açıklamalar pakete eklenmedi (--with-explanations).');
}

main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
});
